alter table public.subscriptions add column last_event_created bigint not null default 0;
create function public.apply_billing_event(event_id text,event_created bigint,account_id uuid,plan text,status_value text,period_end timestamptz,customer_id text,subscription_id text) returns void language plpgsql security invoker set search_path='' as $$begin
 perform pg_advisory_xact_lock(hashtextextended(account_id::text,0));
 if exists(select 1 from public.payment_webhook_events where id=event_id) then return;end if;
 update public.subscriptions set plan_id=plan,status=status_value,current_period_end=period_end,stripe_customer_id=customer_id,stripe_subscription_id=subscription_id,updated_at=now(),last_event_created=event_created where user_id=account_id and last_event_created<=event_created;
 insert into public.payment_webhook_events(id) values(event_id);
end;$$;
revoke all on function public.apply_billing_event(text,bigint,uuid,text,text,timestamptz,text,text) from public,anon,authenticated;
grant execute on function public.apply_billing_event(text,bigint,uuid,text,text,timestamptz,text,text) to service_role;
grant all on public.subscriptions,public.payment_webhook_events to service_role;
create policy webhook_service on payment_webhook_events for all to service_role using(true) with check(true);
